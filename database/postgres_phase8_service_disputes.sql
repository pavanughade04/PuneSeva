
-- PuneSeva - Phase 8: Service Disputes
-- PostgreSQL migration
-- No payment or refund transactions.



CREATE TABLE public.service_disputes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id integer NOT NULL,
    customer_id integer NOT NULL,
    provider_id integer NOT NULL,
    reason varchar(100) NOT NULL,
    description varchar(2000) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending',
    admin_notes varchar(2000),
    reviewed_by integer,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at timestamp without time zone,

    CONSTRAINT service_disputes_booking_unique UNIQUE (booking_id),

    CONSTRAINT service_disputes_status_check
        CHECK (status IN ('pending', 'under_review', 'resolved', 'rejected')),

    CONSTRAINT service_disputes_reason_check
        CHECK (length(trim(reason)) > 0),

    CONSTRAINT service_disputes_description_check
        CHECK (length(trim(description)) > 0),

    CONSTRAINT service_disputes_resolved_at_check
        CHECK (
            (status IN ('resolved', 'rejected') AND resolved_at IS NOT NULL)
            OR
            (status IN ('pending', 'under_review') AND resolved_at IS NULL)
        ),

    CONSTRAINT fk_service_disputes_booking
        FOREIGN KEY (booking_id)
        REFERENCES public.bookings(id) ON DELETE RESTRICT,

    CONSTRAINT fk_service_disputes_customer
        FOREIGN KEY (customer_id)
        REFERENCES public.users(id) ON DELETE RESTRICT,

    CONSTRAINT fk_service_disputes_provider
        FOREIGN KEY (provider_id)
        REFERENCES public.users(id) ON DELETE RESTRICT,

    CONSTRAINT fk_service_disputes_reviewer
        FOREIGN KEY (reviewed_by)
        REFERENCES public.users(id) ON DELETE RESTRICT
);

CREATE INDEX idx_service_disputes_status_created
    ON public.service_disputes(status, created_at DESC);

CREATE INDEX idx_service_disputes_customer
    ON public.service_disputes(customer_id, created_at DESC);

CREATE INDEX idx_service_disputes_provider
    ON public.service_disputes(provider_id, created_at DESC);


CREATE TABLE public.dispute_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id integer NOT NULL,
    previous_status varchar(20),
    new_status varchar(20) NOT NULL,
    actor_id integer NOT NULL,
    actor_role varchar(20) NOT NULL,
    notes varchar(2000),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT dispute_history_previous_check
        CHECK (
            previous_status IS NULL
            OR previous_status IN ('pending', 'under_review', 'resolved', 'rejected')
        ),

    CONSTRAINT dispute_history_new_check
        CHECK (new_status IN ('pending', 'under_review', 'resolved', 'rejected')),

    CONSTRAINT dispute_history_actor_role_check
        CHECK (actor_role IN ('customer', 'admin')),

    CONSTRAINT dispute_history_initial_status_check
        CHECK (
            previous_status IS NOT NULL
            OR (new_status = 'pending' AND actor_role = 'customer')
        ),

    CONSTRAINT fk_dispute_history_dispute
        FOREIGN KEY (dispute_id)
        REFERENCES public.service_disputes(id) ON DELETE RESTRICT,

    CONSTRAINT fk_dispute_history_actor
        FOREIGN KEY (actor_id)
        REFERENCES public.users(id) ON DELETE RESTRICT
);

CREATE INDEX idx_dispute_history_dispute_created
    ON public.dispute_status_history(dispute_id, created_at, id);


